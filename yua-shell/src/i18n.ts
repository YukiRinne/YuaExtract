export function localizeText(text: string, locale: Locale): string {
  if (locale !== "en" || !text) return text;
  const key = text.trim();
  const exact = EN_EXACT[key];
  if (exact) return text.replace(key, exact);
  for (const [re, to] of EN_RULES) {
    if (re.test(text)) return text.replace(re, to);
  }
  return text;
}

